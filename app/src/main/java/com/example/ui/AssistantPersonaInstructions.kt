    "smart-cat" to "Smart Cat",
    "hasan" to "حسن صديق",
    "jana" to "ريتاج صديقة",
    "teacher" to "أ. أحمد",
    "coder" to "H2 Code",
    "doctor" to "د. خالد",
    "business" to "أ. سمير",
    "advisor" to "أ. سمير",
    "legal" to "المستشار عادل",
    "sheikh" to "الشيخ عبد الرحمن",
    "coach" to "الكابتن فهد",
    "designer" to "المصممة آية",
    "chef" to "الشيف مراد",
    "nanny" to "المربية أسماء"
